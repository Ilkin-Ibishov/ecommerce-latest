#!/usr/bin/env node
/**
 * Generates one INDEX.md per documentation directory so a session can find the right file
 * without globbing 1.2 MB of prose. docs/audits alone is 642 KB across 50 files.
 *
 * Usage:
 *   node scripts/docs/build-index.mjs            # write the indexes
 *   node scripts/docs/build-index.mjs --check    # fail if any index is stale (CI)
 *
 * Hand-maintained indexes in a repository that merges three branches a day are wrong by Friday,
 * so this is generated and CI checks it. Every field comes from the file's own content — never
 * from git — so a shallow checkout produces the same bytes as a full clone.
 *
 * Dependency-free on purpose: the invariants job runs before `pnpm install`.
 */
import { readFile, writeFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const CHECK = process.argv.includes('--check');

const ARCHIVED = 'Finished phases only, kept as a record. `.ignore` hides docs/archive/ from project-wide search; search it by path.';
const TARGETS = [
  { dir: 'docs/audits', what: 'Reviews, verdicts and every agent\'s own notes for work still open. Move them to docs/archive/audits/ when the phase merges.' },
  { dir: 'docs/tasks', status: true, what: 'Specs. Architect-owned: agents read them, never edit them. Each carries a `Status:` line under its title (active | deferred); a shipped spec moves to docs/archive/tasks/.' },
  { dir: 'docs/design-notes', what: 'The implementer\'s proposal for a phase, written and reviewed before any code.' },
  { dir: 'prompts', what: 'The launch prompt each builder round was given. A record, not live configuration.' },
  { dir: 'docs/archive/status', what: 'Superseded handoffs. Nothing here is read at session start.' },
  { dir: 'docs/archive/tasks', what: `Specs of merged phases. ${ARCHIVED}` },
  { dir: 'docs/archive/design-notes', what: `Design notes of merged phases. ${ARCHIVED}` },
  { dir: 'docs/archive/audits', what: `Reviews and agent notes of merged phases. ${ARCHIVED}` },
  { dir: 'docs/archive/prompts', what: `Launch prompts of finished builder rounds. ${ARCHIVED}` },
  { dir: 'docs/archive/planning', what: `Storefront roadmap, UI/UX plan and competitor snapshot from May–June 2026; most items shipped. ${ARCHIVED}` },
];

const SKIP = new Set(['INDEX.md', 'README.md']);

/** The first `# ` heading, else the filename. Subject lines are trimmed of trailing punctuation. */
const titleOf = (text, file) => {
  const m = /^#\s+(.+?)\s*$/m.exec(text);
  return (m ? m[1] : path.basename(file, '.md')).replace(/\s+/g, ' ').trim();
};

/**
 * The first sentence of real prose: skips the heading, frontmatter, tables, code fences, lists
 * and bold-only lines, which in this corpus are almost always "Superseded" or "Written <date>"
 * banners rather than the subject.
 */
const subjectOf = (text) => {
  const lines = text.split('\n');
  let inFence = false;
  const out = [];
  for (const raw of lines) {
    const line = raw.trim();
    if (line.startsWith('```')) { inFence = !inFence; continue; }
    if (inFence) continue;
    if (!line || line === '---') continue;
    if (/^#{1,6}\s/.test(line) || line.startsWith('Status:')) continue;
    if (/^[|>*\-+]/.test(line) || /^\d+\./.test(line)) continue;
    out.push(line);
    if (out.join(' ').length > 160) break;
  }
  const prose = out.join(' ').replace(/\s+/g, ' ');
  const sentence = /^(.{20,200}?[.!?])(\s|$)/.exec(prose);
  const picked = sentence ? sentence[1] : prose.slice(0, 160);
  return picked.replace(/\|/g, '\|').trim() || '(no prose)';
};

/** `Status: active|shipped|deferred` within the first lines under the title, else null. */
const statusOf = (text) =>
  /^Status: (active|shipped|deferred)\b/m.exec(text.split('\n').slice(0, 12).join('\n'))?.[1] ?? null;

const kb = (n) => `${Math.max(1, Math.round(n / 1024))} KB`;

async function rowsFor(dir) {
  let names;
  try { names = await readdir(path.join(ROOT, dir)); } catch { return null; }
  const files = names.filter((n) => n.endsWith('.md') && !SKIP.has(n)).sort();
  const rows = [];
  for (const name of files) {
    const text = await readFile(path.join(ROOT, dir, name), 'utf8');
    rows.push({ name, title: titleOf(text, name), subject: subjectOf(text), status: statusOf(text), size: kb(Buffer.byteLength(text)) });
  }
  return rows;
}

const render = (dir, what, rows, withStatus) => {
  const total = rows.length;
  const head = withStatus ? '| File | Status | Title | Subject | Size |\n|---|---|---|---|---|' : '| File | Title | Subject | Size |\n|---|---|---|---|';
  const row = (r) => withStatus
    ? `| [\`${r.name}\`](${r.name}) | ${r.status ?? '**missing**'} | ${r.title} | ${r.subject} | ${r.size} |`
    : `| [\`${r.name}\`](${r.name}) | ${r.title} | ${r.subject} | ${r.size} |`;
  return `<!-- Generated by scripts/docs/build-index.mjs. Do not edit by hand; run \`pnpm run docs:index\`. -->

# ${dir} — index

${what}

${total} file${total === 1 ? '' : 's'}. The subject column is the file's own first sentence, so a
file that opens with a banner reads as one — fix the file, not the index.

${head}
${rows.map(row).join('\n')}
`;
};

let stale = 0;
let written = 0;
const problems = [];
for (const { dir, what, status } of TARGETS) {
  const rows = await rowsFor(dir);
  if (!rows) { console.log(`skip  ${dir} (no such directory)`); continue; }
  if (status) {
    for (const r of rows) {
      if (!r.status) problems.push(`${dir}/${r.name}: no "Status: active|deferred" line under the title`);
      if (r.status === 'shipped') problems.push(`${dir}/${r.name}: shipped — git mv it to docs/archive/tasks/`);
    }
  }
  const target = path.join(ROOT, dir, 'INDEX.md');
  const next = render(dir, what, rows, status);
  let current = null;
  try { current = await readFile(target, 'utf8'); } catch { /* absent */ }
  if (current === next) { console.log(`ok    ${dir}/INDEX.md (${rows.length} files)`); continue; }
  if (CHECK) {
    console.log(`STALE ${dir}/INDEX.md (${rows.length} files)`);
    stale++;
    continue;
  }
  await writeFile(target, next);
  console.log(`write ${dir}/INDEX.md (${rows.length} files)`);
  written++;
}

if (problems.length) {
  console.error(`\nFAILED: ${problems.length} spec status problem(s):\n  ${problems.join('\n  ')}`);
  process.exit(1);
}
if (CHECK && stale) {
  console.error(`\nFAILED: ${stale} index file(s) are stale. Run \`pnpm run docs:index\` and commit the result.`);
  process.exit(1);
}
console.log(CHECK ? '\nAll indexes current.' : `\n${written} index file(s) written.`);
